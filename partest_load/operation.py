"""Операция прогона: то, что нагружали.

Личность прогона — **операция**, а не слаг. Раньше прогон опознавался парой «ключ эндпоинта
+ профиль», где ключ — произвольное имя, придуманное потребителем (`orders-create`). Такое
имя не сводится ни с чем: узел графа выражается методом и путём, а `orders-create`
выражается только догадкой того, кто его читает. Догадка между двумя системами — не связь.

Форма операции — `"МЕТОД /путь"`, то есть ровно то, чем семейство уже опознаёт эндпоинт
(`partest.reports.compare` складывает ключ так же). Путь берётся из описания эндпоинта как
есть, вместе с `{placeholders}`: шаблон пути — это и есть узел, а подставленный
идентификатор — один его вызов.

Операция в имя файла напрямую не годится: в ней есть пробел, косые черты и фигурные скобки.
Поэтому `operation_key` делает из неё безопасное имя — читаемый остаток плюс восемь знаков от
хеша полной операции. Преобразование **не обратимо**, и это сознательно: обратимое
кодирование пути в имя файла — отдельный интерфейс, который пришлось бы сопровождать. Вместо
него операция лежит внутри файла прогона в исходном виде, и читателю не нужно её расшифровывать.
"""

from __future__ import annotations

import hashlib
import re

# Методы, которые могут стоять в операции. Шире, чем принимает описание эндпоинта: операция
# пишется и руками, и пришедшей из спецификации строкой.
OPERATION_METHODS = ("GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS")

# Запрос и якорь в операцию не входят: узел графа — путь операции, а не один её вызов.
OPERATION_RE = re.compile(r"^(?:" + "|".join(OPERATION_METHODS) + r") /[^\s?#]*$")

# Сколько читаемого остатка оставляем в имени каталога. Длинные пути встречаются, а предел
# длины имени файла — нет: хеш всё равно отвечает за различимость.
KEY_READABLE_LIMIT = 48

_UNSAFE = re.compile(r"[^a-z0-9]+")


def normalize_operation(method: str, path: str) -> str:
    """Собрать операцию из метода и пути: `("get", "v1/items")` → `"GET /v1/items"`.

    Приводится только то, что не меняет смысла: регистр метода, ведущая косая черта и
    пробелы по краям. Сам путь не переписывается — пакет не знает, какие его части
    эквивалентны в чужом контракте.
    """
    return f"{str(method).strip().upper()} /{str(path).strip().lstrip('/')}"


def check_operation(value: str) -> str:
    """Вернуть операцию, если она годна; иначе `ValueError` с понятным текстом."""
    operation = str(value or "").strip()
    if not OPERATION_RE.match(operation):
        raise ValueError(
            "операция прогона пишется как «МЕТОД /путь» "
            f"(например «GET /v1/items/{{id}}»), методы: {', '.join(OPERATION_METHODS)}; "
            f"получено: {value!r}"
        )
    return operation


def operation_key(operation: str) -> str:
    """Безопасное имя каталога и файла для операции.

    Читаемая часть нужна человеку, который смотрит в каталог результатов; хеш нужен тому,
    кто туда пишет: две разные операции обязаны лечь в разные места, даже если их читаемые
    части совпали (`/v1/items/{id}` и `/v1/items/{key}` после упрощения — одно и то же).
    """
    operation = check_operation(operation)
    digest = hashlib.sha256(operation.encode("utf-8")).hexdigest()[:8]
    readable = _UNSAFE.sub("-", operation.lower()).strip("-")[:KEY_READABLE_LIMIT].strip("-")
    return f"{readable}-{digest}" if readable else digest
